/**
 * CLI contract (help, version, usage errors, schema) and the hand-off to Architecture Check: the generated
 * workspace.dsl is a declared model Architecture Check accepts without drift.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import * as architectureCheck from "@enwithai/architecture-check";
import { describe, expect, it } from "vitest";
import { TOOL_VERSION } from "../src/version.js";
import { cli, demoRepo, NOW, tempRepo } from "./helpers.js";

describe("CLI", () => {
  it("prints help, version and the schema", async () => {
    const dir = tempRepo({ "a.txt": "x" });
    expect((await cli(["--help"], dir)).stdout).toContain("blueprint-check generate");
    expect((await cli(["--version"], dir)).stdout).toBe(`${TOOL_VERSION}\n`);
    const schema = await cli(["schema"], dir);
    expect(JSON.parse(schema.stdout).title).toMatch(/Blueprint Check documents/);
    const bare = await cli([], dir);
    expect(bare.code).toBe(2);
    expect(bare.stderr).toContain("Usage:");
  });

  it("maps usage mistakes to exit 2", async () => {
    const dir = tempRepo({ "a.txt": "x" });
    for (const args of [
      ["nope"],
      ["generate", "--format", "json"],
      ["generate", "--blueprint", "x"],
      ["generate", "extra"],
      ["check", "--format", "sarif"],
      ["check", "--out-dir", "x"],
      ["generate", "--unknown-flag"],
      ["generate", "--on-error", "maybe"],
      ["generate", "--cwd", "does-not-exist"],
      ["check", "--blueprint", "../outside"],
    ])
      expect((await cli(args, dir)).code, args.join(" ")).toBe(2);
  });

  it("--out-dir and --no-branding shape the output", async () => {
    const dir = demoRepo();
    expect((await cli(["generate", "--out-dir", "docs/bp", "--no-branding", "--quiet"], dir)).code).toBe(0);
    const readme = readFileSync(join(dir, "docs", "bp", "README.md"), "utf8");
    expect(readme).not.toContain("Generated by [Blueprint Check]");
    expect((await cli(["check", "--blueprint", "docs/bp", "--quiet"], dir)).code).toBe(0);
  });

  it("removes stale diagram files on regeneration", async () => {
    const dir = demoRepo();
    mkdirSync(join(dir, "architecture-blueprint", "diagrams"), { recursive: true });
    writeFileSync(join(dir, "architecture-blueprint", "diagrams", "D11-C99.mmd"), "old");
    writeFileSync(join(dir, "architecture-blueprint", "diagrams", "notes.txt"), "keep");
    await cli(["generate", "--quiet"], dir);
    expect(existsSync(join(dir, "architecture-blueprint", "diagrams", "D11-C99.mmd"))).toBe(false);
    expect(existsSync(join(dir, "architecture-blueprint", "diagrams", "notes.txt"))).toBe(true);
  });

  it("--write-model hands the model to Architecture Check, which then reports no drift", async () => {
    const dir = demoRepo();
    const result = await cli(["generate", "--graph", "graph.json", "--write-model"], dir);
    expect(result.code).toBe(0);
    expect(result.stderr).toContain("wrote architecture/workspace.dsl");
    const report = architectureCheck.analyze({
      cwd: dir,
      command: "check",
      config: architectureCheck.DEFAULT_CONFIG,
      graphPath: join(dir, "graph.json"),
      now: NOW,
    });
    expect(report.declared_model?.usable).toBe(true);
    expect(report.policy.result).toBe("pass");
    expect(
      report.findings.filter((f) => f.status === "verified_static_fact" && f.severity !== "info")
    ).toEqual([]);
  });

  it("--write-model never overwrites a declared model", async () => {
    const dir = demoRepo();
    mkdirSync(join(dir, "architecture"), { recursive: true });
    writeFileSync(join(dir, "architecture", "workspace.dsl"), "keep me\n");
    const result = await cli(["generate", "--write-model"], dir);
    expect(result.code).toBe(0);
    expect(result.stderr).toContain("not overwritten");
    expect(readFileSync(join(dir, "architecture", "workspace.dsl"), "utf8")).toBe("keep me\n");
  });

  it("an output path that is a file is a usage error", async () => {
    const dir = demoRepo();
    writeFileSync(join(dir, "taken"), "x");
    expect((await cli(["generate", "--out-dir", "taken", "--quiet"], dir)).code).toBe(2);
  });
});
