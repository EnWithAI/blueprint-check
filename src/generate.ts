/**
 * Orchestration of `generate` (docs/SPEC.md §2): read the sources, build the model, draw the views, assess catalog,
 * coverage and validation, and produce the in-memory blueprint (plus the Structurizr DSL for Architecture Check).
 * Reads files only; writes nothing (see render/files.ts).
 */
import { resolve } from "node:path";
import * as architectureCheck from "@enwithai/architecture-check";
import { readSnapshot } from "./input/git.js";
import { readSources } from "./input/sources.js";
import { assessCatalog, coverageMetrics, coverageUnits, integrity, validationGates } from "./model/assess.js";
import { buildModel } from "./model/build.js";
import { redactDeep } from "./redact.js";
import { buildDiagrams } from "./render/mermaid.js";
import type { Blueprint } from "./types.js";
import { SCHEMA_VERSION } from "./types.js";
import { TOOL_VERSION } from "./version.js";

/** Options for one generate run. Paths are relative to `cwd` or absolute. */
export interface GenerateOptions {
  cwd: string;
  graphPath?: string | null;
  productCheckPath?: string | null;
  architectureConfigPath?: string | null;
  now?: () => Date;
}

/** Keys whose values are ids, hashes or enums and are never redacted. */
const NO_REDACT = new Set([
  "id",
  "evidence_id",
  "excerpt_sha256",
  "sha256",
  "actual_ref",
  "snapshot_ref",
  "kind",
  "status",
  "confidence",
  "evidence_type",
  "source_tool",
  "inspection_status",
]);

/** Generates a blueprint for the repository at `options.cwd`. */
export function generate(options: GenerateOptions): Blueprint {
  const cwd = resolve(options.cwd);
  const now = options.now ?? ((): Date => new Date());
  const sources = readSources({
    cwd,
    graphPath: options.graphPath ?? null,
    productCheckPath: options.productCheckPath ?? null,
    architectureConfigPath: options.architectureConfigPath ?? null,
    now,
  });
  const snapshot = readSnapshot(cwd);
  const core = buildModel(cwd, sources, snapshot);
  const diagrams = buildDiagrams(core);
  const catalog = assessCatalog(core, diagrams);
  const units = coverageUnits(core, diagrams);
  const metrics = coverageMetrics(core, units, diagrams, catalog);
  const problems = integrity(core, diagrams);
  const gates = validationGates(core, diagrams, catalog, problems);
  core.registry.link([
    ...core.components,
    ...core.relationships,
    ...core.data_stores,
    ...core.contracts,
    ...core.findings,
  ]);
  const structural = core.components.some((c) => c.kind === "container" || c.kind === "component");

  const model = redactDeep(
    {
      schema_version: SCHEMA_VERSION,
      kind: "blueprint-architecture-model" as const,
      tool: { name: "blueprint-check" as const, version: TOOL_VERSION },
      generated_at: now().toISOString(),
      system_name: core.repository.label,
      overall_status: structural ? ("PROVISIONAL" as const) : ("BLOCKED" as const),
      inputs: {
        architecture_check: { version: architectureCheck.TOOL_VERSION, config: sources.architectureConfig },
        graph: sources.graph,
        product_check: sources.product,
      },
      repositories: [core.repository],
      components: core.components,
      relationships: core.relationships,
      data_stores: core.data_stores,
      contracts: core.contracts,
      journeys: [] as never[],
      diagrams: diagrams.map(({ mermaid: _mermaid, ...rest }) => rest),
      findings: core.findings,
      gaps: core.gaps,
      catalog,
    },
    NO_REDACT
  );
  const dsl = [
    `// Generated by Blueprint Check ${TOOL_VERSION} with Architecture Check ${architectureCheck.TOOL_VERSION} from the as-built model.`,
    "// Review it, then commit it as architecture/workspace.dsl: Architecture Check will report drift against it.",
    architectureCheck.renderDsl(sources.asBuilt).trimEnd(),
    "",
  ].join("\n");
  return {
    model,
    evidence: redactDeep(
      {
        schema_version: SCHEMA_VERSION,
        kind: "blueprint-evidence-register" as const,
        citation_format: "repo_id@snapshot_ref:relative_path:Lline_start-Lline_end",
        evidence: core.registry.records,
      },
      NO_REDACT
    ),
    coverage: redactDeep(
      {
        schema_version: SCHEMA_VERSION,
        kind: "blueprint-coverage-ledger" as const,
        units,
        metrics,
        denominator_note:
          "Denominators are bounded by what the input tools discovered in one repository; undiscovered elements may remain. Metrics are never combined into a score.",
      },
      NO_REDACT
    ),
    validation: { schema_version: SCHEMA_VERSION, kind: "blueprint-validation-report", gates },
    diagrams,
    dsl,
  };
}
