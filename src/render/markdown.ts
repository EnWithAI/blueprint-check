/**
 * Markdown renderings (docs/SPEC.md §6): the dossier (ARCHITECTURE_BLUEPRINT.md), the package README, the open
 * questions and the drift report of `check`. Every repository-derived string is escaped (`code` or `text`).
 */
import type { Blueprint, CatalogEntry, Component, Diagram, DriftReport, EvidenceRecord } from "../types.js";
import { TOOL_VERSION } from "../version.js";
import { code, text } from "./escape.js";

/** Rendering options. */
export interface MarkdownOptions {
  branding: boolean;
}

const FOOTER =
  "\n---\n\nGenerated by [Blueprint Check](https://github.com/enwithai/blueprint-check), part of the EnWithAI Engineering Commons (MIT). Deterministic and offline: no code executed, no network, no AI model.\n";

/** Inline citation of evidence ids with their locations. */
function cite(ids: string[], evidence: Map<string, EvidenceRecord>, max = 3): string {
  const parts = ids.slice(0, max).map((id) => {
    const e = evidence.get(id);
    if (!e) return code(id);
    const lines =
      e.line_start === null
        ? ""
        : `:L${e.line_start}${e.line_end !== null && e.line_end !== e.line_start ? `-L${e.line_end}` : ""}`;
    return `${code(id)} ${code(`${e.relative_path}${lines}`)}`;
  });
  if (ids.length > max) parts.push(`+${ids.length - max} more`);
  return parts.join("; ") || "none";
}

const mermaid = (d: Diagram): string =>
  `\`\`\`mermaid\n${d.mermaid.trimEnd()}\n\`\`\`\n\nSource: [${d.artifact_path}](${d.artifact_path})${d.omitted_nodes > 0 ? ` · ${d.omitted_nodes} elements beyond the node budget are listed in architecture-model.json` : ""}\n`;

/** One catalog section: status, reason and the views produced for it. */
function section(entry: CatalogEntry, diagrams: Diagram[]): string {
  const out = [
    `### ${entry.catalog_id} ${text(entry.name)}`,
    "",
    `**Status:** ${entry.status}. ${text(entry.reason)}`,
    "",
  ];
  for (const d of diagrams.filter((k) => k.catalog_id === entry.catalog_id)) {
    if (d.id !== entry.catalog_id) out.push(`**${d.id}: ${text(d.title)}**`, "");
    out.push(mermaid(d));
  }
  return out.join("\n");
}

/** The dossier. */
export function renderDossier(bp: Blueprint, options: MarkdownOptions): string {
  const { model, coverage, validation, diagrams } = bp;
  const evidence = new Map(bp.evidence.evidence.map((e) => [e.evidence_id, e]));
  const repo = model.repositories[0];
  const out: string[] = [];
  out.push(`# ${text(model.system_name)}: as-built architecture blueprint`, "");
  out.push(
    `**Overall status:** ${model.overall_status} · **Snapshot:** ${repo?.actual_ref ? code(repo.actual_ref.slice(0, 12)) : "unknown"}${repo?.branch ? ` on ${code(repo.branch)}` : ""} · **Generated:** ${model.generated_at.slice(0, 10)} by Blueprint Check ${TOOL_VERSION} · **Basis:** static, deterministic derivation`,
    ""
  );
  out.push(
    "This blueprint is generated from evidence that Architecture Check" +
      (model.inputs.graph ? ", the Impact Check module graph" : "") +
      (model.inputs.product_check ? " and Product Check" : "") +
      " found in the repository. Views that need judgment (journeys, trust enforcement, operations) are marked blocked, not invented. IDs resolve in `architecture-model.json`; evidence ids in `evidence-register.json`.",
    ""
  );
  out.push("## 1. Survey", "", "| Input | Used | Detail |", "|---|---|---|");
  out.push(
    `| Architecture Check derive | yes | ${code(`${model.inputs.architecture_check.version}, config ${model.inputs.architecture_check.config}`)} |`
  );
  out.push(
    `| Impact Check module graph | ${model.inputs.graph ? "yes" : "no"} | ${model.inputs.graph ? code(model.inputs.graph.path) : "components and import edges not derived"} |`
  );
  out.push(
    `| Product Check surface | ${model.inputs.product_check ? "yes" : "no"} | ${model.inputs.product_check ? code(model.inputs.product_check.path) : "endpoints, pages, entities not derived"} |`,
    ""
  );
  const counts = [
    `${model.components.filter((c) => c.kind === "container").length} containers`,
    `${model.components.filter((c) => c.kind === "component").length} components`,
    `${model.components.filter((c) => c.kind === "external_system").length} external systems`,
    `${model.data_stores.length} data stores`,
    `${model.contracts.length} contracts`,
    `${model.relationships.length} relationships`,
    `${bp.evidence.evidence.length} evidence records`,
  ];
  out.push(`Derived: ${counts.join(" · ")}.`, "");

  out.push("## 2. Views", "");
  for (const entry of model.catalog) out.push(section(entry, diagrams));

  out.push(
    "## 3. Elements",
    "",
    "| ID | Name | Kind | Implementation | Evidence | Confidence |",
    "|---|---|---|---|---|---|"
  );
  const row = (c: Component): string =>
    `| ${c.id} | ${text(c.name)} | ${c.kind} | ${
      c.implementation_paths
        .slice(0, 2)
        .map((p) => code(p))
        .join(", ") || "n/a"
    } | ${cite(c.evidence_ids, evidence, 2)} | ${c.confidence} |`;
  out.push(...model.components.map(row));
  for (const s of model.data_stores)
    out.push(
      `| ${s.id} | ${text(s.name)} | data store | ${
        s.schema_paths
          .slice(0, 2)
          .map((p) => code(p))
          .join(", ") || "n/a"
      } | ${cite(s.evidence_ids, evidence, 2)} | ${s.confidence} |`
    );
  out.push(
    "",
    "## 4. Relationships",
    "",
    "| ID | From | To | Purpose | Evidence | Confidence |",
    "|---|---|---|---|---|---|"
  );
  for (const r of model.relationships)
    out.push(
      `| ${r.id} | ${r.source_id} | ${r.target_id} | ${text(r.purpose)} | ${cite(r.evidence_ids, evidence, 2)} | ${r.confidence} |`
    );
  if (model.contracts.length) {
    out.push(
      "",
      "## 5. Contracts",
      "",
      "| ID | Kind | Producer | Definition | Items | Evidence |",
      "|---|---|---|---|---|---|"
    );
    for (const ct of model.contracts)
      out.push(
        `| ${ct.id} | ${ct.kind}${ct.version_if_proven ? ` ${text(ct.version_if_proven)}` : ""} | ${ct.producer_ids.join(", ") || "unowned"} | ${ct.definition_paths
          .slice(0, 2)
          .map((p) => code(p))
          .join(", ")} | ${ct.items} | ${cite(ct.evidence_ids, evidence, 2)} |`
      );
  }
  out.push("", "## 6. Observations", "");
  if (model.findings.length === 0) out.push("No rule-based observation applies.");
  else {
    out.push("| ID | Rule | Observation | Evidence | Confidence |", "|---|---|---|---|---|");
    for (const f of model.findings)
      out.push(
        `| ${f.id} | ${code(f.rule_id)} | ${text(f.observation)} ${text(f.impact)} | ${cite(f.evidence_ids, evidence, 2)} | ${f.confidence} |`
      );
  }
  out.push(
    "",
    "## 7. Coverage",
    "",
    "| Metric | Numerator | Denominator | Percent | Note |",
    "|---|---|---|---|---|"
  );
  for (const m of coverage.metrics)
    out.push(
      `| ${m.name} | ${m.numerator} | ${m.denominator} | ${m.percent === null ? "n/a" : `${m.percent}%`} | ${text(m.note)} |`
    );
  out.push(
    "",
    text(coverage.denominator_note),
    "",
    "## 8. Validation",
    "",
    "| Gate | Check | Status | Evidence |",
    "|---|---|---|---|"
  );
  for (const g of validation.gates)
    out.push(`| ${g.id} | ${g.check} | ${g.status} | ${text(g.evidence, { maxLength: 300 })} |`);
  out.push(
    "",
    "## 9. Hand-off to Architecture Check",
    "",
    "`workspace.dsl` in this folder is the as-built model in Structurizr DSL. Review it, keep what is intended, and commit it as `architecture/workspace.dsl`. From then on `architecture-check check` reports every change in the code that the model does not describe, and `blueprint-check check` reports when this blueprint's evidence goes stale.",
    ""
  );
  return `${out.join("\n")}${options.branding ? FOOTER : ""}`;
}

/** The package README. */
export function renderReadme(bp: Blueprint, options: MarkdownOptions): string {
  const { model, coverage } = bp;
  const produced = model.catalog.filter((c) => c.status === "produced").length;
  const partial = model.catalog.filter((c) => c.status === "partial").length;
  const blocked = model.catalog.filter((c) => c.status === "blocked").length;
  const na = model.catalog.filter((c) => c.status === "not_applicable").length;
  const lines = [
    `# Architecture blueprint: ${text(model.system_name)}`,
    "",
    `**Overall status: ${model.overall_status}.** Generated ${model.generated_at.slice(0, 10)} by Blueprint Check ${TOOL_VERSION}. Views: ${produced} produced, ${partial} partial, ${blocked} blocked (need judgment), ${na} not applicable.`,
    "",
    "| File | Contents |",
    "|---|---|",
    "| [ARCHITECTURE_BLUEPRINT.md](ARCHITECTURE_BLUEPRINT.md) | The dossier: every catalog view, elements, relationships, contracts, observations, coverage, validation |",
    `| [diagrams/](diagrams/) | ${bp.diagrams.length} Mermaid views |`,
    "| [architecture-model.json](architecture-model.json) | Canonical model |",
    "| [evidence-register.json](evidence-register.json) | Evidence with hashed cited lines |",
    "| [coverage-ledger.json](coverage-ledger.json) | Units, exclusions and metrics |",
    "| [validation-report.json](validation-report.json) | Gates V01-V13 |",
    "| [workspace.dsl](workspace.dsl) | Structurizr model for Architecture Check |",
    "| [OPEN_QUESTIONS.md](OPEN_QUESTIONS.md) | Gaps and what would resolve them |",
    "",
    "## Coverage",
    "",
    ...coverage.metrics.map(
      (m) =>
        `- ${m.name}: ${m.denominator === 0 ? "n/a" : `${m.numerator}/${m.denominator}`} (${text(m.note)})`
    ),
    "",
    "Keep it current: `blueprint-check check` reports evidence whose cited lines changed and elements that appeared or disappeared.",
    "",
  ];
  return `${lines.join("\n")}${options.branding ? FOOTER : ""}`;
}

/** The open questions: gaps ranked by criticality, then observations to confirm. */
export function renderOpenQuestions(bp: Blueprint, options: MarkdownOptions): string {
  const rank = { high: 0, medium: 1, low: 2 } as const;
  const gaps = [...bp.model.gaps].sort(
    (a, b) => rank[a.criticality] - rank[b.criticality] || (a.id < b.id ? -1 : 1)
  );
  const lines = [
    "# Open questions",
    "",
    "| # | Gap | Criticality | What would resolve it |",
    "|---|---|---|---|",
  ];
  gaps.forEach((g, i) =>
    lines.push(
      `| ${i + 1} | ${g.id} ${text(g.description)} | ${g.criticality} | ${text(g.confirmation_needed)} |`
    )
  );
  const toConfirm = bp.model.findings.filter((f) => f.confidence !== "CONFIRMED");
  if (toConfirm.length) {
    lines.push("", "## Observations to confirm", "");
    for (const f of toConfirm)
      lines.push(`- ${f.id} ${text(f.observation)} ${text(f.optional_recommendation ?? "")}`);
  }
  lines.push("");
  return `${lines.join("\n")}${options.branding ? FOOTER : ""}`;
}

/** The drift report of `check`. */
export function renderDriftMarkdown(report: DriftReport, options: MarkdownOptions): string {
  const e = report.evidence;
  const m = report.model;
  const lines = [
    "# Blueprint Check: drift",
    "",
    `**Result:** ${report.result === "current" ? "current" : "**stale**"} · blueprint ${code(report.blueprint.path)} generated ${report.blueprint.generated_at.slice(0, 10)} (Blueprint Check ${text(report.blueprint.tool_version)})`,
    "",
    `Evidence: ${e.unchanged} unchanged, ${e.changed} changed, ${e.missing} missing (of ${e.total}).`,
    "",
    `Model: ${m.added_components.length} components added, ${m.removed_components.length} removed; ${m.added_relationships.length} relationships added, ${m.removed_relationships.length} removed.`,
    "",
  ];
  if (e.items.length) {
    lines.push("| Evidence | Location | State |", "|---|---|---|");
    for (const item of e.items.slice(0, 200))
      lines.push(
        `| ${item.evidence_id} | ${code(`${item.path}${item.line_start === null ? "" : `:L${item.line_start}`}`)} | ${item.state} |`
      );
    if (e.items.length > 200) lines.push(`| … | ${e.items.length - 200} more in the JSON report | |`);
    lines.push("");
  }
  for (const [name, list] of [
    ["Components added", m.added_components],
    ["Components removed", m.removed_components],
    ["Relationships added", m.added_relationships],
    ["Relationships removed", m.removed_relationships],
  ] as const)
    if (list.length)
      lines.push(
        `**${name}:** ${list
          .slice(0, 50)
          .map((k) => code(k))
          .join(", ")}`,
        ""
      );
  if (report.result === "stale")
    lines.push("Regenerate with `blueprint-check generate` and review the diff.", "");
  return `${lines.join("\n")}${options.branding ? FOOTER : ""}`;
}
